"""Regenerate packaging/homebrew/orlog.rb for a released version.

Reads the checksums straight from the GitHub release assets, so the
formula can never claim a sha256 that doesn't match what was published --
the failure mode of hand-editing, and one Homebrew reports to users as a
checksum mismatch rather than as a maintainer error.

Usage:
    python packaging/homebrew/bump.py 0.0.4
    python packaging/homebrew/bump.py 0.0.3 --check   # verify, don't write

Then copy the result into the tap repo (mrrasmussendk/homebrew-tap) at
Formula/orlog.rb.

Design decision: the per-platform blocks are GENERATED between the
`# <platforms>` markers, not patched in place. The release workflow builds
four binaries now, and which of them exist is a property of the release,
not of the formula -- so a platform whose asset is missing gets an `odie`
with a working alternative, and one that appears gets a url/sha256 pair,
without anyone having to remember to add or remove a block. Patching could
only ever update blocks that already existed, which is how a formula ends
up permanently telling Intel Mac users to go to PyPI after the Intel build
starts shipping.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

FORMULA = Path(__file__).with_name("orlog.rb")
REPO = "mrrasmussendk/Orlog"
BEGIN = "  # <platforms>"
END = "  # </platforms>"


@dataclass(frozen=True)
class Platform:
    os_block: str  # "on_macos" | "on_linux"
    arch_block: str  # "on_arm" | "on_intel"
    asset_os: str
    asset_arch: str
    # What to tell someone on this platform when no binary was published.
    fallback: str

    @property
    def label(self) -> str:
        return f"{self.asset_os}-{self.asset_arch}"

    def filename(self, version: str) -> str:
        return f"orlog-{version}-{self.asset_os}-{self.asset_arch}.zip"


# Ordered as they should appear in the formula.
PLATFORMS = (
    Platform("on_macos", "on_arm", "macos", "arm64", "pipx install orlog"),
    Platform("on_macos", "on_intel", "macos", "x86_64", "pipx install orlog"),
    Platform("on_linux", "on_intel", "linux", "x86_64", "pipx install orlog"),
    Platform("on_linux", "on_arm", "linux", "arm64", "pipx install orlog"),
)


def _asset_url(version: str, filename: str) -> str:
    return f"https://github.com/{REPO}/releases/download/v{version}/{filename}"


def _sha256_of(url: str) -> str | None:
    """The asset's sha256, or None if the release doesn't have it.

    A missing asset is a normal state -- a release built before a platform
    was added to the matrix simply doesn't have it -- so it produces an
    `odie` block rather than failing the bump.
    """
    try:
        with urllib.request.urlopen(url) as response:  # noqa: S310 - a fixed github.com URL
            digest = hashlib.sha256()
            for chunk in iter(lambda: response.read(1 << 20), b""):
                digest.update(chunk)
            return digest.hexdigest()
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None
        raise


def _arch_block(platform: Platform, version: str, checksum: str | None) -> list[str]:
    if checksum is None:
        return [
            f"    {platform.arch_block} do",
            f'      odie "orlog has no {platform.label} binary for v{version} -- install from PyPI instead: {platform.fallback}"',
            "    end",
        ]
    return [
        f"    {platform.arch_block} do",
        f'      url "{_asset_url(version, platform.filename(version))}"',
        f'      sha256 "{checksum}"',
        "    end",
    ]


def render_platforms(version: str, checksums: dict[str, str | None]) -> str:
    lines = [BEGIN, "  # Generated by packaging/homebrew/bump.py -- do not hand-edit."]
    for os_block in ("on_macos", "on_linux"):
        lines.append(f"  {os_block} do")
        blocks = [p for p in PLATFORMS if p.os_block == os_block]
        for index, platform in enumerate(blocks):
            if index:
                lines.append("")
            lines.extend(_arch_block(platform, version, checksums[platform.label]))
        lines.append("  end")
        if os_block == "on_macos":
            lines.append("")
    lines.append(END)
    return "\n".join(lines)


def fetch_checksums(version: str) -> dict[str, str | None]:
    checksums: dict[str, str | None] = {}
    for platform in PLATFORMS:
        filename = platform.filename(version)
        print(f"  fetching {platform.label}: {filename}", file=sys.stderr)
        checksums[platform.label] = _sha256_of(_asset_url(version, filename))
        if checksums[platform.label] is None:
            print(f"    not published for v{version}; the formula will odie on this platform", file=sys.stderr)
    return checksums


def render(version: str, checksums: dict[str, str | None]) -> str:
    text = FORMULA.read_text(encoding="utf-8")
    text = re.sub(r'^  version "[^"]+"$', f'  version "{version}"', text, count=1, flags=re.M)

    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[:start] + render_platforms(version, checksums) + text[end:]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("version", help="release version WITHOUT the leading v, e.g. 0.0.4")
    parser.add_argument("--check", action="store_true", help="verify the formula is already correct")
    args = parser.parse_args()

    checksums = fetch_checksums(args.version)
    if all(c is None for c in checksums.values()):
        print(f"no orlog assets at all for v{args.version} -- is the release published?", file=sys.stderr)
        return 1

    updated = render(args.version, checksums)
    current = FORMULA.read_text(encoding="utf-8")

    if args.check:
        if updated == current:
            print(f"formula is up to date for {args.version}")
            return 0
        print(f"formula does NOT match the published {args.version} assets", file=sys.stderr)
        return 1

    FORMULA.write_text(updated, encoding="utf-8")
    print(f"wrote {FORMULA} for {args.version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
